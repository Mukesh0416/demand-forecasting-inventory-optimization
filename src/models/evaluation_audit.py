"""
Milestone 11 - Evaluation Audit & Error Analysis
================================================

Purpose
-------
Audit the model comparison pipeline before any performance claim is made.
The latest ML experiment reported:

    Random Forest Test MAE = 1.1120
    XGBoost Test MAE       = 1.1136
    MA-28 Test MAE         = 1.1501

while the original baseline experiment reported:

    MA-28 Test MAE = 1.1157

This script investigates the discrepancy, builds a common evaluation
population, independently recalculates every metric, and produces all audit
artifacts required by Milestone 11.

Discrepancy diagnosis (MA-28: 1.1157 -> 1.1501)
------------------------------------------------
1. Original baseline (src/models/baseline_forecasting.py)
   MA-28 for date t = mean of the previous 28 actual demands (shift 1),
   computed per date as a rolling window over the full history. Evaluated on
   the demand_dev test population (192 dates x 300 ids = 57,600 rows) it gives
   MAE = 1.115702.

2. Latest ML run (ml_results.csv / ml_predictions.parquet 'ma28_prediction')
   The stored MA-28 predictions were generated by:

       df.groupby('id')['demand'].shift(1).tail(28).groupby('id').mean()

   i.e. a SINGLE constant per product/store series equal to the mean of the
   last 28 days ending at the second-to-last day of the ENTIRE features
   dataset (April 2016, which is inside the test period), applied to every
   test row. This is:
       (a) a look-ahead leak  - the window uses future test-period data, and
       (b) not a per-date rolling forecast - the prediction never changes.
   It yields MAE = 1.150091 (test) / 1.146617 (validation), reproducing the
   ml_results.csv values exactly (verified bit-for-bit).

3. The two numbers are NOT comparable. The audited leakage-safe MA-28 on the
   common features population (rolling shift(1).rolling(28).mean()) is
   1.113810 (test) / 1.081952 (validation).

Therefore the previously claimed ~3.3% improvement over MA-28 is INVALID.
This script recomputes all metrics apples-to-apples on the common population.

ML prediction source
--------------------
The audit uses the ORIGINAL saved ML results as the authoritative ML
performance:
  * Random Forest / XGBoost test predictions: ml_predictions.parquet
  * Random Forest / XGBoost validation metrics: ml_results.csv (validation
    predictions were not persisted by the original run)
Re-training the models in this environment does NOT reproduce the saved test
predictions exactly (RandomForestRegressor / XGBRegressor behavioural drift
across library versions), so re-trained predictions are never substituted for
the authoritative saved ones. See docs/MODEL_EVALUATION.md section 8.
"""

