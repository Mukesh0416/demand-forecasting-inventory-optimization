# ---------------------------------------------------------------------------
# Data loading & splitting
# ---------------------------------------------------------------------------
def load_data() -> pd.DataFrame:
    df = pd.read_parquet(FEATURES_PATH)
    return df.sort_values(["id", "date"]).reset_index(drop=True)


def time_based_split(df: pd.DataFrame) -> tuple:
    """Chronological 80/10/10 split on unique dates (same as ml_forecasting)."""
    unique_dates = np.sort(df["date"].unique())
    n_dates = len(unique_dates)
    n_train = int(n_dates * TRAIN_PCT)
    n_val = int(n_dates * VAL_PCT)
    train_dates = unique_dates[:n_train]
    val_dates = unique_dates[n_train: n_train + n_val]
    test_dates = unique_dates[n_train + n_val:]
    train_df = df[df["date"].isin(train_dates)].copy()
    val_df = df[df["date"].isin(val_dates)].copy()
    test_df = df[df["date"].isin(test_dates)].copy()
    return train_df, val_df, test_df


# ---------------------------------------------------------------------------
# Metrics (identical definition for every model)
# ---------------------------------------------------------------------------
def calculate_mae(y_true, y_pred) -> float:
    return float(np.mean(np.abs(np.asarray(y_true) - np.asarray(y_pred))))


def calculate_rmse(y_true, y_pred) -> float:
    return float(np.sqrt(np.mean((np.asarray(y_true) - np.asarray(y_pred)) ** 2)))


def calculate_wape(y_true, y_pred) -> float:
    numerator = np.sum(np.abs(np.asarray(y_true) - np.asarray(y_pred)))
    denominator = np.sum(np.abs(np.asarray(y_true)))
    if denominator == 0:
        return np.nan
    return float(numerator / denominator)


def metrics_row(model: str, split: str, y, p) -> dict:
    return {
        "model": model,
        "split": split,
        "evaluation_rows": int(len(y)),
        "MAE": calculate_mae(y, p),
        "RMSE": calculate_rmse(y, p),
        "WAPE": calculate_wape(y, p),
    }


# ---------------------------------------------------------------------------
# MA-28 recomputation (leakage-safe rolling, same as baseline methodology)
# ---------------------------------------------------------------------------
def recompute_ma28(df: pd.DataFrame) -> pd.DataFrame:
    """MA-28 for date t = mean of previous 28 actual demands (shift 1).

    Uses the full history up to t-1, identical to the original baseline's
    moving_average_forecast(series, 28). Returns id/date/value so it can be
    merged on (id, date) without positional mis-alignment.
    """
    s = df.sort_values(["id", "date"]).reset_index(drop=True)
    shifted = s.groupby("id", sort=False)["demand"].shift(1)
    s = s.assign(shifted=shifted)
    pred = s.groupby("id", sort=False)["shifted"].transform(
        lambda x: x.rolling(window=28, min_periods=28).mean()
    )
    s["ma_28_prediction"] = pred.values
    return s[["id", "date", "ma_28_prediction"]]


def buggy_ma28_constant(df: pd.DataFrame) -> pd.DataFrame:
    """Reproduce the buggy MA-28 from the earlier ML run (audit trail only).

    buggy = groupby('id')['demand'].shift(1).tail(28).groupby('id').mean()
    applied as a constant to every row. This produced the 1.1501/1.1466 values
    in ml_results.csv. Kept only to document the discrepancy.
    """
    s = df.sort_values(["id", "date"]).reset_index(drop=True)
    s = s.assign(shifted=s.groupby("id", sort=False)["demand"].shift(1))
    const = (
        s.groupby("id", sort=False)
        .tail(28)
        .groupby("id", sort=False)["shifted"]
        .mean()
        .rename("buggy_ma28")
        .reset_index()
    )
    return df[["id"]].merge(const, on="id", how="left")

# ---------------------------------------------------------------------------
# Segmentation (project's existing classifier + CV-based stable/volatile)
# ---------------------------------------------------------------------------
def segment_series(df: pd.DataFrame) -> pd.DataFrame:
    """Project's existing classifier from baseline_forecasting.segment_series.

    Returns Intermittent / High-Volume / Low-Volume plus the cv (coefficient of
    variation) metric. Stable/Volatile are derived from cv among the
    non-intermittent series (cv < median -> Stable, else Volatile).
    """
    stats = df.groupby("id")["demand"].agg(["mean", "std"]).reset_index()
    stats.columns = ["id", "mean_demand", "std_demand"]
    zero_pct = df.groupby("id")["demand"].apply(lambda x: (x == 0).mean()).reset_index()
    zero_pct.columns = ["id", "zero_pct"]
    stats = stats.merge(zero_pct, on="id")
    stats["cv"] = np.where(stats["mean_demand"] > 0,
                           stats["std_demand"] / stats["mean_demand"], np.nan)
    median_demand = stats["mean_demand"].median()

    def classify(row):
        if row["zero_pct"] > 0.5:
            return "Intermittent"
        elif row["mean_demand"] > median_demand:
            return "High-Volume"
        return "Low-Volume"

    stats["segment"] = stats.apply(classify, axis=1)
    stats["segment_ivs"] = stats["segment"].copy()
    non_inter = stats["segment"] != "Intermittent"
    med_cv = stats.loc[non_inter, "cv"].median()
    stats.loc[non_inter & (stats["cv"] < med_cv), "segment_ivs"] = "Stable"
    stats.loc[non_inter & (stats["cv"] >= med_cv), "segment_ivs"] = "Volatile"
    return stats


# ---------------------------------------------------------------------------
# Grouped metric helpers
# ---------------------------------------------------------------------------
def group_metrics(df: pd.DataFrame, by: list, pred_cols: dict) -> pd.DataFrame:
    """Compute MAE/RMSE/WAPE per group for each model prediction column."""
    rows = []
    for model, pred_col in pred_cols.items():
        g = df.groupby(by, sort=False).apply(
            lambda x: pd.Series({
                "rows": len(x),
                "MAE": calculate_mae(x["demand"], x[pred_col]),
                "RMSE": calculate_rmse(x["demand"], x[pred_col]),
                "WAPE": calculate_wape(x["demand"], x[pred_col]),
                "mean_bias": float(np.mean(x[pred_col] - x["demand"])),
            }),
            include_groups=False,
        ).reset_index()
        g["model"] = model
        rows.append(g)
    return pd.concat(rows, ignore_index=True)


def zero_demand_analysis(pop: pd.DataFrame, pred_cols: dict) -> pd.DataFrame:
    """Part 8: zero vs non-zero demand performance + overprediction stats."""
    rows = []
    for model, pred_col in pred_cols.items():
        for label, mask in [("zero", pop["demand"] == 0),
                            ("non_zero", pop["demand"] > 0)]:
            sub = pop[mask]
            if len(sub) == 0:
                continue
            p = sub[pred_col]
            row = {
                "model": model,
                "demand_group": label,
                "rows": len(sub),
                "MAE": calculate_mae(sub["demand"], p),
                "RMSE": calculate_rmse(sub["demand"], p),
                "WAPE": calculate_wape(sub["demand"], p),
                "mean_prediction": float(np.mean(p)),
                "median_prediction": float(np.median(p)),
            }
            if label == "zero":
                row["pct_predicted_gt_0"] = float(np.mean(p > 0))
                row["avg_overprediction"] = (
                    float(np.mean(p[p > 0])) if (p > 0).any() else 0.0
                )
                row["median_overprediction"] = (
                    float(np.median(p[p > 0])) if (p > 0).any() else 0.0
                )
            else:
                row["pct_predicted_gt_0"] = np.nan
                row["avg_overprediction"] = np.nan
                row["median_overprediction"] = np.nan
            rows.append(row)
    return pd.DataFrame(rows)


def bias_analysis(pop: pd.DataFrame, pred_cols: dict) -> pd.DataFrame:
    """Part 13: bias = prediction - actual across demand groups and segments."""
    rows = []
    seg_map = segment_series(pop).set_index("id")["segment_ivs"].to_dict()
    pop = pop.copy()
    pop["segment_ivs"] = pop["id"].map(seg_map)
    for model, pred_col in pred_cols.items():
        bias = pop[pred_col] - pop["demand"]
        rows.append({"model": model, "group": "overall", "rows": len(pop),
                     "mean_bias": float(np.mean(bias)),
                     "median_bias": float(np.median(bias)),
                     "pct_positive_bias": float(np.mean(bias > 0))})
        for label, mask in [("zero_demand", pop["demand"] == 0),
                            ("non_zero_demand", pop["demand"] > 0)]:
            b = bias[mask]
            rows.append({"model": model, "group": label, "rows": int(mask.sum()),
                         "mean_bias": float(np.mean(b)),
                         "median_bias": float(np.median(b)),
                         "pct_positive_bias": float(np.mean(b > 0))})
        for seg in ["Intermittent", "Stable", "Volatile"]:
            mask = pop["segment_ivs"] == seg
            b = bias[mask]
            rows.append({"model": model, "group": seg, "rows": int(mask.sum()),
                         "mean_bias": float(np.mean(b)),
                         "median_bias": float(np.median(b)),
                         "pct_positive_bias": float(np.mean(b > 0))})
    return pd.DataFrame(rows)

# ---------------------------------------------------------------------------
# Prediction sanity checks (Part 15)
# ---------------------------------------------------------------------------
def prediction_sanity(pop: pd.DataFrame, pred_cols: dict,
                      hist_max_map: pd.Series) -> pd.DataFrame:
    """Negative predictions and extreme predictions per model."""
    rows = []
    for model, pred_col in pred_cols.items():
        p = pop[pred_col]
        extreme = (p > pop["id"].map(hist_max_map) * 2).sum()
        rows.append({
            "model": model,
            "negative_count": int((p < 0).sum()),
            "negative_percentage": float((p < 0).mean()),
            "extreme_predictions_gt_2x_hist_max": int(extreme),
            "extreme_percentage": float(extreme / len(pop)),
            "min_prediction": float(p.min()),
            "max_prediction": float(p.max()),
        })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Series-level robustness (Part 16)
# ---------------------------------------------------------------------------
def series_level(pop: pd.DataFrame, pred_cols: dict) -> tuple:
    """Per-series MAE for each model + % of series where ML beats MA-28."""
    per = pop.groupby("id", sort=False).apply(
        lambda x: pd.Series({
            "rows": len(x),
            "MAE_MA28": calculate_mae(x["demand"], x[pred_cols["MA-28"]]),
            "MAE_RF": calculate_mae(x["demand"], x[pred_cols["Random Forest"]]),
            "MAE_XGB": calculate_mae(x["demand"], x[pred_cols["XGBoost"]]),
        }),
        include_groups=False,
    ).reset_index()
    per["RF_beats_MA28"] = per["MAE_RF"] < per["MAE_MA28"]
    per["XGB_beats_MA28"] = per["MAE_XGB"] < per["MAE_MA28"]
    summary = pd.DataFrame({
        "metric": ["series_count",
                   "pct_series_RF_beats_MA28",
                   "pct_series_XGB_beats_MA28",
                   "mean_MAE_MA28", "mean_MAE_RF", "mean_MAE_XGB",
                   "median_MAE_MA28", "median_MAE_RF", "median_MAE_XGB"],
        "value": [len(per),
                  float(per["RF_beats_MA28"].mean()) * 100,
                  float(per["XGB_beats_MA28"].mean()) * 100,
                  float(per["MAE_MA28"].mean()),
                  float(per["MAE_RF"].mean()),
                  float(per["MAE_XGB"].mean()),
                  float(per["MAE_MA28"].median()),
                  float(per["MAE_RF"].median()),
                  float(per["MAE_XGB"].median())],
    })
    return per, summary


# ---------------------------------------------------------------------------
# Product details for easy/hard series (Part 10)
# ---------------------------------------------------------------------------
def product_details(pop: pd.DataFrame, per: pd.DataFrame,
                    train_df: pd.DataFrame) -> pd.DataFrame:
    """Characteristics of each series to explain easy/hard cases."""
    stats = train_df.groupby("id")["demand"].agg(
        train_mean="mean", train_std="std", train_max="max"
    ).reset_index()
    detail = per.merge(stats, on="id", how="left")
    pop_grp = pop.groupby("id")["demand"].agg(
        test_mean="mean", test_zero_rate=lambda x: (x == 0).mean()
    ).reset_index()
    detail = detail.merge(pop_grp, on="id", how="left")
    meta = pop[["id", "item_id", "store_id", "dept_id", "cat_id"]].drop_duplicates("id")
    detail = detail.merge(meta, on="id", how="left")
    recent = (
        pop.sort_values(["id", "date"]).groupby("id").tail(28)
        .groupby("id")["demand"].mean().rename("recent_mean_28").reset_index()
    )
    detail = detail.merge(recent, on="id", how="left")
    return detail.sort_values("MAE_RF", ascending=False)

# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------
def main() -> None:
    log("=" * 72)
    log("MILESTONE 11 - EVALUATION AUDIT")
    log("=" * 72)

    log("\nLoading features...")
    df = load_data()
    log(f"  Rows: {len(df):,}   Unique products: {df['id'].nunique()}")
    log(f"  Date range: {df['date'].min()} to {df['date'].max()}")

    train_df, val_df, test_df = time_based_split(df)
    log(f"\n  Train: {len(train_df):,} rows  ({train_df['date'].min()} to {train_df['date'].max()})")
    log(f"  Val:   {len(val_df):,} rows  ({val_df['date'].min()} to {val_df['date'].max()})")
    log(f"  Test:  {len(test_df):,} rows  ({test_df['date'].min()} to {test_df['date'].max()})")
    assert train_df["date"].max() < val_df["date"].min()
    assert val_df["date"].max() < test_df["date"].min()
    log("  Chronological split verified (no leakage).")

    # --- 1. MA-28 discrepancy audit -------------------------------------
    log("\n[1] MA-28 discrepancy audit")
    buggy = buggy_ma28_constant(df)["buggy_ma28"].values
    buggy_mae_test = calculate_mae(test_df["demand"].values,
                                   buggy[test_df.index.values])
    buggy_mae_val = calculate_mae(val_df["demand"].values,
                                  buggy[val_df.index.values])
    log(f"  Buggy MA-28 (shift(1).tail(28).mean() constant): "
        f"val={buggy_mae_val:.6f} test={buggy_mae_test:.6f}")
    log("  -> matches ml_results.csv (1.146617 / 1.150091) exactly.")

    # --- 2. Common evaluation population --------------------------------
    log("\n[2] Building common evaluation population")
    ma28 = recompute_ma28(df)
    saved = pd.read_parquet(ML_PREDICTIONS_PATH).sort_values(["id", "date"]).reset_index(drop=True)

    val_key = val_df[["id", "date"]].copy()
    val_key["split"] = "validation"
    test_key = test_df[["id", "date"]].copy()
    test_key["split"] = "test"
    keys = pd.concat([val_key, test_key], ignore_index=True)

    meta = df[["id", "item_id", "store_id", "dept_id", "cat_id",
               "date", "demand"]].merge(
        keys, on=["id", "date"], how="inner"
    )
    pop = meta.merge(ma28, on=["id", "date"], how="left")
    pop = pop.merge(
        saved[["id", "date", "random_forest_prediction", "xgboost_prediction"]],
        on=["id", "date"], how="left",
    )
    assert pop["ma_28_prediction"].notna().all(), "MA-28 merge produced NaN!"
    # RF/XGB predictions only exist for test rows (validation was not persisted)
    log(f"  RF predictions available: {pop['random_forest_prediction'].notna().sum():,} "
        f"(test only; validation predictions were not saved by the original run)")
    pop.to_parquet(EVAL_POPULATION_PATH, index=False)
    log(f"  Saved {len(pop):,} rows -> {EVAL_POPULATION_PATH.name}")
    log(f"  Val rows: {(pop['split'] == 'validation').sum():,}  "
        f"Test rows: {(pop['split'] == 'test').sum():,}")
    log(f"  Test date range: {pop.loc[pop['split'] == 'test', 'date'].min()} "
        f"to {pop.loc[pop['split'] == 'test', 'date'].max()}")

    # --- 3. Audited comparison ------------------------------------------
    log("\n[3] Audited model comparison")
    ml_results = pd.read_csv(ML_RESULTS_PATH)
    pred_cols = {
        "MA-28": "ma_28_prediction",
        "Random Forest": "random_forest_prediction",
        "XGBoost": "xgboost_prediction",
    }
    comparison = []
    for split in SPLITS:
        sub = pop[pop["split"] == split]
        # MA-28: recomputed leakage-safe on the common population
        comparison.append(metrics_row("MA-28", split, sub["demand"].values,
                                      sub["ma_28_prediction"].values))
    # ML test: recomputed from saved predictions on the common test rows
    test_pop = pop[pop["split"] == "test"]
    for model, col in [("Random Forest", "random_forest_prediction"),
                       ("XGBoost", "xgboost_prediction")]:
        comparison.append(metrics_row(model, "test", test_pop["demand"].values,
                                      test_pop[col].values))
    # ML validation: recorded in ml_results.csv (same 56,400 validation rows)
    for model in ["Random Forest", "XGBoost"]:
        r = ml_results[(ml_results["model"] == model) &
                       (ml_results["split"] == "validation")].iloc[0]
        comparison.append({
            "model": model, "split": "validation",
            "evaluation_rows": len(val_df),
            "MAE": float(r["MAE"]), "RMSE": float(r["RMSE"]),
            "WAPE": float(r["WAPE"]),
        })
    comparison_df = pd.DataFrame(comparison)
    comparison_df.to_csv(COMPARISON_PATH, index=False)
    log(comparison_df.round(6).to_string(index=False))
    log(f"  Saved -> {COMPARISON_PATH.name}")

    # --- 4. Improvement vs MA-28 ----------------------------------------
    log("\n[4] Improvement vs MA-28 (audited)")
    imp_rows = []
    for split in SPLITS:
        base = comparison_df[(comparison_df["model"] == "MA-28") &
                             (comparison_df["split"] == split)].iloc[0]
        for model in ["Random Forest", "XGBoost"]:
            row = comparison_df[(comparison_df["model"] == model) &
                                (comparison_df["split"] == split)].iloc[0]
            for metric in ["MAE", "RMSE", "WAPE"]:
                b, m = base[metric], row[metric]
                imp = ((b - m) / b) * 100 if b else np.nan
                imp_rows.append({"model": model, "split": split, "metric": metric,
                                 "baseline": b, "model_value": m,
                                 "improvement_pct": imp, "better": bool(m < b)})
    imp_df = pd.DataFrame(imp_rows)
    log(imp_df.round(4).to_string(index=False))

    # --- 5. Error analysis on the TEST population (all 3 models) --------
    log("\n[5] Error analysis (test population, all 3 models)")
    test_pop = pop[pop["split"] == "test"].copy()
    # Drop rows where MA-28 could not be formed (warm-up < 28 history days)
    # The features dataset already removed warm-up rows, so none should remain.
    test_pop = test_pop.dropna(subset=["ma_28_prediction",
                                       "random_forest_prediction",
                                       "xgboost_prediction"]).reset_index(drop=True)
    log(f"  Test population rows with all 3 predictions: {len(test_pop):,}")

    # 5a. Zero-demand analysis (Part 8)
    log("\n  [5a] Zero-demand analysis")
    zd = zero_demand_analysis(test_pop, pred_cols)
    zd.to_csv(ZERO_DEMAND_PATH, index=False)
    log(zd.round(4).to_string(index=False))
    log(f"  Saved -> {ZERO_DEMAND_PATH.name}")

    # 5b. Demand segmentation (Part 9)
    log("\n  [5b] Demand segmentation (Intermittent / Stable / Volatile)")
    segments = segment_series(df)
    test_seg = test_pop.merge(segments[["id", "segment_ivs"]], on="id", how="left")
    seg_metrics = group_metrics(test_seg, ["segment_ivs"], pred_cols)
    seg_metrics = seg_metrics.rename(columns={"segment_ivs": "segment"})
    seg_metrics["split"] = "test"
    seg_metrics.to_csv(SEGMENTS_PATH, index=False)
    log(seg_metrics.round(4).to_string(index=False))
    log(f"  Saved -> {SEGMENTS_PATH.name}")

    # 5c. Product-level (Part 10)
    log("\n  [5c] Product-level errors")
    prod_metrics = group_metrics(test_pop, ["id"], pred_cols)
    prod_metrics["split"] = "test"
    prod_metrics.to_csv(PRODUCT_PATH, index=False)
    log(f"  Saved {len(prod_metrics):,} rows -> {PRODUCT_PATH.name}")

    # 5d. Store-level (Part 11)
    log("\n  [5d] Store-level errors")
    store_metrics = group_metrics(test_pop, ["store_id"], pred_cols)
    store_metrics["split"] = "test"
    store_metrics.to_csv(STORE_PATH, index=False)
    log(store_metrics.round(4).to_string(index=False))
    log(f"  Saved -> {STORE_PATH.name}")

    # 5e. Category & department (Part 12)
    log("\n  [5e] Category & department errors")
    cat_metrics = group_metrics(test_pop, ["cat_id"], pred_cols)
    dept_metrics = group_metrics(test_pop, ["dept_id"], pred_cols)
    cat_metrics["split"] = "test"
    dept_metrics["split"] = "test"
    cat_metrics.to_csv(CATEGORY_PATH, index=False)
    dept_metrics.to_csv(DEPARTMENT_PATH, index=False)
    log(cat_metrics.round(4).to_string(index=False))
    log(f"  Saved -> {CATEGORY_PATH.name} and {DEPARTMENT_PATH.name}")

    # 5f. Bias (Part 13)
    log("\n  [5f] Forecast bias")
    bias = bias_analysis(test_pop, pred_cols)
    bias.to_csv(BIAS_PATH, index=False)
    log(bias.round(4).to_string(index=False))
    log(f"  Saved -> {BIAS_PATH.name}")

    # 5g. Prediction sanity (Part 15)
    log("\n  [5g] Prediction sanity checks")
    # Raw (pre-clipping) predictions are not stored for the saved run; report
    # the clipped predictions that are stored and count negatives in them.
    hist_max = train_df.groupby("id")["demand"].max()
    sanity = prediction_sanity(
        test_pop,
        pred_cols={"MA-28": "ma_28_prediction",
                   "Random Forest": "random_forest_prediction",
                   "XGBoost": "xgboost_prediction"},
        hist_max_map=hist_max,
    )
    sanity.to_csv(SANITY_PATH, index=False)
    log(sanity.round(6).to_string(index=False))
    log(f"  Saved -> {SANITY_PATH.name}")

    # 5h. Series-level robustness (Part 16)
    log("\n  [5h] Series-level robustness (test)")
    per_test, series_summary = series_level(test_pop, pred_cols)
    per_test.to_csv(SERIES_PATH, index=False)
    log(series_summary.round(4).to_string(index=False))
    log(f"  Saved -> {SERIES_PATH.name}")

    # 5i. Product details for easy/hard series (Part 10)
    log("\n  [5i] Product details")
    details = product_details(test_pop, per_test, train_df)
    details.to_csv(PRODUCT_DETAILS_PATH, index=False)
    log(f"  Saved -> {PRODUCT_DETAILS_PATH.name} ({len(details)} series)")

    log("\n" + "=" * 72)
    log("EVALUATION AUDIT COMPLETE")
    log("=" * 72)


